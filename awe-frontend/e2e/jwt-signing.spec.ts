import { createHmac, generateKeyPairSync, verify } from 'node:crypto'
import { expect, test, type Page } from '@playwright/test'

const encode = (value: unknown) => Buffer.from(JSON.stringify(value)).toString('base64url')
async function openJwt(page: Page) {
  await page.goto('/projects')
  await page.getByLabel('Username').fill(process.env.E2E_USERNAME!)
  await page.locator('input[autocomplete="current-password"]').fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByLabel('Dashboard options')).toBeVisible()
  const projects = await (await page.request.get('/api/v1/projects')).json()
  await page.goto(`/projects/${projects[0].id}/jwt`)
}

async function openSigner(page: Page) {
  await page.getByLabel('JWT options').click()
  await page.getByRole('button', { name: 'Sign edited JWT', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Sign edited JWT' })).toBeVisible()
}

test('edited JSON generates a verifiable compact JWT and copyable request header', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await openJwt(page)
  await page.getByLabel('JWT input token').fill(`${encode({ alg: 'HS256', typ: 'JWT' })}.${encode({ sub: 'original' })}.`)
  await page.getByRole('button', { name: 'Parse', exact: true }).click()
  await page.getByLabel('JWT header JSON').fill(JSON.stringify({ alg: 'HS256', typ: 'JWT', kid: 'edited-key' }))
  await page.getByLabel('JWT payload JSON').fill(JSON.stringify({ sub: '研究者', role: 'editor' }))
  await expect(page.getByRole('dialog', { name: 'Sign edited JWT' })).not.toBeVisible()
  await openSigner(page)
  const signer = page.getByRole('region', { name: 'JWT signing' })
  const secret = 'local-only-jwt-signing-fixture'
  await signer.getByLabel('Signing secret', { exact: true }).fill(secret)
  await signer.getByRole('button', { name: 'Sign and generate JWT' }).click()
  const token = await signer.getByLabel('Generated compact JWT').inputValue()
  const [header, payload, signature] = token.split('.')
  expect(signature).toBe(createHmac('sha256', secret).update(`${header}.${payload}`).digest('base64url'))
  expect(JSON.parse(Buffer.from(payload, 'base64url').toString())).toEqual({ sub: '研究者', role: 'editor' })
  await signer.getByRole('button', { name: 'Copy JWT', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(token)
  await signer.getByRole('button', { name: 'Copy Bearer header' }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(`Authorization: Bearer ${token}`)
  expect(await page.evaluate(value => Object.values(localStorage).some(item => item.includes(value)), secret)).toBe(false)
  await page.getByLabel('Close JWT signing dialog').click()
  await page.getByLabel('JWT payload JSON').fill('{"sub":"new-edit"}')
  await openSigner(page)
  await expect(signer.getByRole('button', { name: 'Copy JWT', exact: true })).toBeDisabled()
  await expect(signer.getByRole('status')).toContainText('Inputs changed')
  await signer.getByRole('button', { name: 'Sign and generate JWT' }).click()
  await signer.getByRole('button', { name: 'Use as input token' }).click()
  await expect(page.getByRole('dialog', { name: 'Sign edited JWT' })).not.toBeVisible()
  await expect(page.getByLabel('JWT input token')).toHaveValue(await page.locator('.jwt-signed-result textarea').inputValue())
  await openSigner(page)
  await expect(signer.getByRole('button', { name: 'Copy JWT', exact: true })).toBeEnabled()
  await page.getByLabel('Close JWT signing dialog').click()
  await page.getByLabel('JWT payload JSON').fill('{invalid')
  await openSigner(page)
  await signer.getByRole('button', { name: 'Sign and generate JWT' }).click()
  await expect(signer.getByRole('alert')).toContainText('Payload must be valid JSON')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await signer.evaluate(element => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Sign edited JWT' })).not.toBeVisible()
  await page.getByLabel('JWT options').click()
  await page.getByRole('button', { name: 'Clear', exact: true }).first().click()
  await openSigner(page)
  await expect(signer.getByLabel('Generated compact JWT')).not.toBeVisible()
  await expect(signer.getByLabel('Signing secret', { exact: true })).toHaveValue('')
})

test('private-key signing preserves RSA algorithm and produces an independently verifiable JWT', async ({ page }) => {
  await openJwt(page)
  const { privateKey, publicKey } = generateKeyPairSync('rsa', { modulusLength: 2048 })
  await page.getByLabel('JWT input token').fill(`${encode({ alg: 'RS256', typ: 'JWT' })}.${encode({ sub: 'rsa-fixture' })}.`)
  await page.getByRole('button', { name: 'Parse', exact: true }).click()
  await openSigner(page)
  const signer = page.getByRole('region', { name: 'JWT signing' })
  await expect(signer.getByLabel('Signing algorithm')).toHaveValue('RS256')
  await signer.getByLabel('Signing private key').fill(privateKey.export({ type: 'pkcs8', format: 'pem' }).toString())
  await signer.getByRole('button', { name: 'Sign and generate JWT' }).click()
  const token = await signer.getByLabel('Generated compact JWT').inputValue()
  const [header, payload, signature] = token.split('.')
  expect(JSON.parse(Buffer.from(header, 'base64url').toString()).alg).toBe('RS256')
  expect(verify('sha256', Buffer.from(`${header}.${payload}`), publicKey, Buffer.from(signature, 'base64url'))).toBe(true)
})

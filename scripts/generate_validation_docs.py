"""Regenerate the operator-facing matrix from versioned coverage metadata."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'dockerfiles/awe_validation/coverage.json').read_text())
lines = [
    '---', 'title: Vulnerability coverage matrix',
    'summary: Verified detector fixtures, existing scanner adapters, prerequisites, and remaining gaps.',
    'order: 57', '---', '# Vulnerability coverage matrix', '',
    f"Suite version: {data['suite_version']}. This file is generated by `scripts/generate_validation_docs.py`.", '',
    data['verification_note'], '',
    'Use **Transforms → ⋮ → Coverage matrix** for a searchable view with current registration status.', '',
    'A completed run means execution completed. A candidate is not a confirmed finding; verified behavior still needs an application-policy and impact assessment. A negative result never establishes complete vulnerability coverage.', '',
    '| Area | Family | Transforms | Detector evidence | Required inputs | Limits |',
    '| --- | --- | --- | --- | --- | --- |',
]
labels = {'fixture_verified': 'Controlled positive / negative fixtures', 'adapter_only': 'Adapter only', 'manual_required': 'Manual / partial'}
escape = lambda value: str(value).replace('|', '\\|').replace('\n', ' ')
for row in data['rows']:
    columns = [row['area'], row['family'], ', '.join(f'`{key}`' for key in row['tool_keys']) or 'No dedicated transform', labels[row['verification']], '; '.join(row['inputs']), row['limitations']]
    lines.append('| ' + ' | '.join(escape(value) for value in columns) + ' |')
lines += ['', '## Verification sources', '',
          '- `awe-backend/tests/test_validation_suite.py`: every native profile has controlled vulnerable/protected cases, transport/evidence checks, and opt-in Docker execution.',
          '- `awe-frontend/e2e/validation-coverage.spec.ts`: catalog discovery, coverage filters, real tool execution, report artifacts, and evidence capture.',
          '- [OWASP WSTG v4.2](https://wstg.owasp.org/v4.2/4-Web_Application_Security_Testing/): testing-family reference, not a claim of WSTG conformance.',
          '- [CWE catalog](https://cwe.mitre.org/data/index.html): weakness identifiers, not confirmation of impact.',
          '- [Nuclei template execution](https://docs.projectdiscovery.io/opensource/nuclei/running) and [SQLmap usage](https://github.com/sqlmapproject/sqlmap/wiki/Usage): existing adapter capabilities remain dependent on configuration and target context.', '']
destination = ROOT / 'awe-frontend/src/docs/vulnerability-coverage.md'
destination.write_text('\n'.join(lines))
